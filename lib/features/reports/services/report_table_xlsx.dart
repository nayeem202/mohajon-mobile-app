Uint8List buildTableXlsx(ReportTableData table) {
  final archive = Archive()
    ..addFile(
      ArchiveFile(
        '[Content_Types].xml',
        _contentTypesXml.length,
        utf8.encode(_contentTypesXml),
      ),
    )
    ..addFile(
      ArchiveFile(
        '_rels/.rels',
        _rootRelationshipsXml.length,
        utf8.encode(_rootRelationshipsXml),
      ),
    )
    ..addFile(
      ArchiveFile(
        'xl/workbook.xml',
        _workbookXml(table.title).length,
        utf8.encode(_workbookXml(table.title)),
      ),
    )
    ..addFile(
      ArchiveFile(
        'xl/_rels/workbook.xml.rels',
        _workbookRelationshipsXml.length,
        utf8.encode(_workbookRelationshipsXml),
      ),
    )
    ..addFile(
      ArchiveFile('xl/styles.xml', _stylesXml.length, utf8.encode(_stylesXml)),
    )
    ..addFile(
      ArchiveFile(
        'xl/worksheets/sheet1.xml',
        _worksheetXml(table).length,
        utf8.encode(_worksheetXml(table)),
      ),
    );

  return Uint8List.fromList(ZipEncoder().encode(archive)!);
}

String _worksheetXml(ReportTableData table) {
  final columnCount = table.columns.length;
  final rows = <String>[];
  var rowIndex = 1;
  final headerRow = 4;
  final dataStart = headerRow + 1;
  final lastDataRow = table.rows.isEmpty
      ? dataStart
      : dataStart + table.rows.length - 1;

  rows.add(_row(rowIndex++, [_textCell('A1', table.title, styleId: 1)]));
  rows.add(_row(rowIndex++, [_textCell('A2', table.subtitle, styleId: 2)]));
  rows.add(_row(rowIndex++, []));
  rows.add(
    _row(headerRow, [
      for (var c = 0; c < columnCount; c++)
        _textCell(
          '${_colLetter(c)}$headerRow',
          table.columns[c].header,
          styleId: 6,
        ),
    ]),
  );

  var dataRow = dataStart;
  for (final data in table.rows) {
    final style = dataRow.isOdd ? 7 : 8;
    rows.add(
      _row(dataRow, [
        for (var c = 0; c < columnCount; c++)
          _dataCell(
            '${_colLetter(c)}$dataRow',
            data[table.columns[c].key],
            styleId: style,
          ),
      ]),
    );
    dataRow++;
  }

  if (table.rows.isEmpty) {
    rows.add(
      _row(dataRow, [
        _textCell('A$dataRow', 'No data in the selected period', styleId: 3),
      ]),
    );
    dataRow++;
  }

  var footerRow = 0;
  if (table.rows.isNotEmpty) {
    rows.add(_row(dataRow++, []));
    footerRow = dataRow;
    rows.add(
      _row(footerRow, [
        _textCell(
          'A$footerRow',
          'Generated by Mohajon on ${DateFormat('dd MMM yyyy').format(DateTime.now())}',
          styleId: 10,
        ),
      ]),
    );
  }

  final cols = <String>[];
  for (var c = 0; c < columnCount; c++) {
    final width = table.columns[c].weight * 16;
    cols.add(
      '<col min="${c + 1}" max="${c + 1}" width="$width" customWidth="1"/>',
    );
  }

  final lastCol = _colLetter(columnCount - 1);
  final merges = footerRow == 0
      ? '<mergeCell ref="A1:$lastCol${1}"/><mergeCell ref="A2:$lastCol${2}"/>'
      : '<mergeCell ref="A1:$lastCol${1}"/><mergeCell ref="A2:$lastCol${2}"/><mergeCell ref="A$footerRow:$lastCol$footerRow"/>';
  return '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetViews>
    <sheetView workbookViewId="0"/>
  </sheetViews>
  <sheetFormatPr defaultRowHeight="15"/>
  <cols>
    ${cols.join()}
  </cols>
  <sheetData>
    ${rows.join()}
  </sheetData>
  <mergeCells count="${footerRow == 0 ? 2 : 3}">
    $merges
  </mergeCells>
  <autoFilter ref="A$headerRow:$lastCol$lastDataRow"/>
</worksheet>
''';
}

String _dataCell(String ref, Object? value, {int? styleId}) {
  final style = styleId == null ? '' : ' s="$styleId"';
  if (value is num) {
    return '<c r="$ref"$style><v>${value.toStringAsFixed(value % 1 == 0 ? 0 : 2)}</v></c>';
  }
  if (value is DateTime) {
    return '<c r="$ref"$style t="inlineStr"><is><t>${_escapeXml(DateFormat('dd MMM yyyy').format(value))}</t></is></c>';
  }
  return '<c r="$ref"$style t="inlineStr"><is><t>${_escapeXml(value?.toString() ?? '')}</t></is></c>';
}

String _row(int index, List<String> cells) =>
    '<row r="$index">${cells.join()}</row>';

String _textCell(String ref, String value, {int? styleId}) {
  final style = styleId == null ? '' : ' s="$styleId"';
  return '<c r="$ref"$style t="inlineStr"><is><t>${_escapeXml(value)}</t></is></c>';
}

String _colLetter(int index) {
  var letter = '';
  var value = index;
  while (value >= 0) {
    letter = String.fromCharCode(65 + (value % 26)) + letter;
    value = (value ~/ 26) - 1;
  }
  return letter;
}

String _escapeXml(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');

