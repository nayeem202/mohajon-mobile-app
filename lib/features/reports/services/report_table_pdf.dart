import 'dart:typed_data';

import 'package:flutter/services.dart' show rootBundle;
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../models/table_report.dart';

Future<Uint8List> buildTablePdf(ReportTableData table) async {
  final theme = await _buildTheme();
  final doc = pw.Document(theme: theme);
  final now = DateTime.now();

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      header: (context) => _header(table.title),
      footer: (context) => _pageFooter(context),
      build: (context) => [
        pw.Text(
          table.subtitle,
          style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600),
        ),
        pw.SizedBox(height: 10),
        _dataTable(table),
        pw.SizedBox(height: 12),
        pw.Text(
          'Generated by Haalkhata on ${DateFormat('dd MMM yyyy').format(now)}',
          textAlign: pw.TextAlign.right,
          style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
        ),
      ],
    ),
  );

  return doc.save();
}

pw.Widget _dataTable(ReportTableData table) {
  final totalWeight = table.columns.fold<double>(
    0,
    (sum, column) => sum + column.weight,
  );
  final tableWidth = PdfPageFormat.a4.availableWidth - 64;
  final columnWidths = <int, pw.TableColumnWidth>{};
  for (var index = 0; index < table.columns.length; index++) {
    final column = table.columns[index];
    columnWidths[index] = pw.FixedColumnWidth(
      tableWidth * column.weight / totalWeight,
    );
  }

  return pw.Table(
    columnWidths: columnWidths,
    border: pw.TableBorder.all(
      color: const PdfColor.fromInt(0xFFE8DDD2),
      width: 0.5,
    ),
    children: [
      pw.TableRow(
        decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF97316)),
        children: [
          for (final column in table.columns)
            pw.Container(
              padding: const pw.EdgeInsets.symmetric(
                horizontal: 4,
                vertical: 5,
              ),
              child: pw.Text(
                column.header,
                textAlign: column.rightAlign
                    ? pw.TextAlign.right
                    : pw.TextAlign.left,
                style: pw.TextStyle(
                  fontSize: 9,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.white,
                ),
              ),
            ),
        ],
      ),
      for (var r = 0; r < table.rows.length; r++)
        pw.TableRow(
          decoration: pw.BoxDecoration(
            color: r.isOdd
                ? const PdfColor.fromInt(0xFFFFF8F1)
                : const PdfColor.fromInt(0xFFFFFFFF),
          ),
          children: [
            for (final column in table.columns)
              pw.Container(
                padding: const pw.EdgeInsets.symmetric(
                  horizontal: 4,
                  vertical: 4,
                ),
                child: pw.Text(
                  _cellText(table.rows[r][column.key]),
                  textAlign: column.rightAlign
                      ? pw.TextAlign.right
                      : pw.TextAlign.left,
                  style: const pw.TextStyle(fontSize: 9),
                ),
              ),
          ],
        ),
    ],
  );
}

String _cellText(Object? value) {
  if (value == null) return '';
  if (value is num) return NumberFormat('#,##0.00').format(value);
  if (value is DateTime) return DateFormat('dd MMM yyyy').format(value);
  return value.toString();
}

pw.Widget _header(String title) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    children: [
      pw.Text(
        'HAALKHATA',
        style: pw.TextStyle(
          fontSize: 14,
          fontWeight: pw.FontWeight.bold,
          color: PdfColor.fromInt(0xFFF97316),
          letterSpacing: 2,
        ),
      ),
      pw.Text(
        title,
        style: pw.TextStyle(
          fontSize: 14,
          fontWeight: pw.FontWeight.bold,
          color: PdfColor.fromInt(0xFF101828),
        ),
      ),
    ],
  );
}

pw.Widget _pageFooter(pw.Context context) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    children: [
      pw.Text(
        'Haalkhata report',
        style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
      ),
      pw.Text(
        'Page ${context.pageNumber} of ${context.pagesCount}',
        style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
      ),
    ],
  );
}

pw.Font? _baseFont;
pw.Font? _boldFont;

Future<pw.ThemeData> _buildTheme() async {
  if (_baseFont == null) {
    final regular = await rootBundle.load(
      'assets/fonts/NotoSansBengali-Regular.ttf',
    );
    _baseFont = pw.Font.ttf(regular);
  }
  if (_boldFont == null) {
    final bold = await rootBundle.load('assets/fonts/NotoSansBengali-Bold.ttf');
    _boldFont = pw.Font.ttf(bold);
  }
  return pw.ThemeData.withFont(base: _baseFont!, bold: _boldFont!);
}
